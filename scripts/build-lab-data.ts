/* ==========================================================================
   LAB DATA BUILD

   Turns the RAG index (23 real chunks of Dheeraj's CV, FAQ, intros and
   project write-ups, each with a 384-dimension bge-small-en-v1.5 embedding)
   into a small module the Lab instruments can import: content/lab-data.ts.

   Two pieces of maths run here rather than in the browser, and for the same
   reason in both cases — the inputs never change between deploys, so paying
   for them at request time would be paying twice for one answer:

     1. PCA down to two dimensions, so the embedding map can plot the corpus.
        The 384-float vectors are 94 KB of JSON; the projected coordinates are
        under 2 KB. Shipping the vectors to project them client-side would
        cost forty times the payload to compute a constant.

     2. A byte-pair-encoding merge table trained on the same 23 chunks, so the
        tokeniser instrument runs a real BPE rather than importing a 2 MB
        production vocabulary or faking it with a regex.

   Run:  npm run build:lab
   Input:  the staged RAG index (see INDEX_CANDIDATES below)
   Output: content/lab-data.ts

   The generated file is committed. It is deterministic given the same index,
   so a diff in it always means the corpus changed.
   ========================================================================== */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

/* --- Input ---------------------------------------------------------------- */

/** The index lives outside the repo (it is generated by the RAG pipeline), so
    look in the places it is staged rather than hardcoding one path. */
const INDEX_CANDIDATES = [
  process.env.LAB_INDEX,
  '/mnt/user-data/uploads/dev/portfolio-scaffold/portfolio/public/index.json',
  join(process.cwd(), 'public/index.json'),
  join(process.cwd(), 'content/lab-index.json'),
].filter((path): path is string => typeof path === 'string' && path.length > 0)

const OUT_PATH = resolve(process.cwd(), 'content/lab-data.ts')

type Chunk = {
  id: string
  source: string
  text: string
  embedding: number[]
}

function loadIndex(): Chunk[] {
  const found = INDEX_CANDIDATES.find((path) => existsSync(path))
  if (!found) {
    console.error('build-lab-data: no index.json found. Looked in:')
    for (const path of INDEX_CANDIDATES) console.error(`  ${path}`)
    console.error('Set LAB_INDEX=/path/to/index.json to point at it.')
    process.exit(1)
  }

  const parsed: unknown = JSON.parse(readFileSync(found, 'utf8'))
  if (!Array.isArray(parsed)) {
    console.error(`build-lab-data: ${found} is not an array of chunks.`)
    process.exit(1)
  }

  const chunks: Chunk[] = []
  for (const raw of parsed) {
    if (typeof raw !== 'object' || raw === null) continue
    const record = raw as Record<string, unknown>
    const { id, source, text, embedding } = record
    if (
      typeof id !== 'string' ||
      typeof source !== 'string' ||
      typeof text !== 'string' ||
      !Array.isArray(embedding)
    ) {
      console.error(`build-lab-data: chunk ${String(id)} is malformed.`)
      process.exit(1)
    }
    chunks.push({ id, source, text, embedding: embedding.map(Number) })
  }

  if (chunks.length === 0) {
    console.error('build-lab-data: index contained no usable chunks.')
    process.exit(1)
  }

  // Every vector must share a dimension or the covariance is meaningless.
  const dims = new Set(chunks.map((c) => c.embedding.length))
  if (dims.size !== 1) {
    console.error(`build-lab-data: mixed embedding dimensions (${[...dims].join(', ')}).`)
    process.exit(1)
  }

  console.log(`build-lab-data: read ${chunks.length} chunks from ${found}`)
  return chunks
}

/* ==========================================================================
   PCA, FROM SCRATCH

   ── WHY NOT A LIBRARY ──────────────────────────────────────────────────────
   The obvious move is UMAP or t-SNE, and both would produce prettier
   clusters. Both are also stochastic, non-linear and have no inverse: there
   is no honest way to say what an axis MEANS, and no way to place a new point
   without re-fitting the whole embedding. PCA is a rotation. The axes are
   real directions in the 384-dimension space, the projection is a dot
   product, and the amount of structure it throws away is a number that can be
   printed rather than hand-waved. For an instrument whose entire point is
   showing what actually happens, reproducible and explainable beats pretty.

   ── WHY THE GRAM MATRIX AND NOT THE COVARIANCE ─────────────────────────────
   The covariance of 384-dimension data is a 384x384 matrix. With only 23
   samples its rank is at most 22, so 362 of those dimensions are structurally
   empty — iterating on it would be 280 times the arithmetic for identical
   answers. The Gram matrix G = X·Xᵗ is 23x23 and shares the same non-zero
   eigenvalues. Power iteration on it converges in milliseconds, and the
   projected scores fall out directly:

     G = X·Xᵗ,  G·u = λ·u,  v = Xᵗ·u / ‖Xᵗ·u‖ = Xᵗ·u / √λ
     scores = X·v = X·Xᵗ·u / √λ = λ·u / √λ = √λ · u

   so the first principal-component coordinate of every chunk is just √λ·u —
   no 384-dimension multiply needed. The component vector v is still computed,
   because it is what lets a future query be projected onto the same axes.

   ── WHY DEFLATION RATHER THAN A FULL EIGENSOLVER ───────────────────────────
   Only two components are wanted. Subtracting λ₁·u₁·u₁ᵗ from G removes the
   first component's contribution entirely, so a second power iteration on the
   deflated matrix finds the second. Two iterations, no eigensolver, and the
   result is exact to within the iteration tolerance.
   ========================================================================== */

/** Matrix-vector product for a symmetric n x n matrix stored row-major. */
function matVec(matrix: Float64Array, n: number, vector: Float64Array): Float64Array {
  const out = new Float64Array(n)
  for (let i = 0; i < n; i += 1) {
    let sum = 0
    const rowStart = i * n
    for (let j = 0; j < n; j += 1) sum += (matrix[rowStart + j] ?? 0) * (vector[j] ?? 0)
    out[i] = sum
  }
  return out
}

function norm(vector: Float64Array): number {
  let sum = 0
  for (let i = 0; i < vector.length; i += 1) sum += (vector[i] ?? 0) ** 2
  return Math.sqrt(sum)
}

/**
 * Dominant eigenpair of a symmetric matrix by power iteration.
 *
 * The starting vector is deterministic (a fixed low-discrepancy pattern rather
 * than Math.random) so two builds of the same corpus produce byte-identical
 * output. A random start would flip signs between runs and make every rebuild
 * look like a content change in the diff.
 */
function powerIteration(
  matrix: Float64Array,
  n: number,
  iterations = 2000,
  tolerance = 1e-12,
): { value: number; vector: Float64Array } {
  /* Annotated as bare `Float64Array` on purpose: that resolves to
     Float64Array<ArrayBufferLike>, which is what matVec returns, so the
     reassignment below type-checks without a cast. */
  let vector: Float64Array = new Float64Array(n)
  for (let i = 0; i < n; i += 1) vector[i] = Math.sin(i + 1) + 0.5

  let magnitude = norm(vector)
  for (let i = 0; i < n; i += 1) vector[i] = (vector[i] ?? 0) / magnitude

  let value = 0
  for (let step = 0; step < iterations; step += 1) {
    const next = matVec(matrix, n, vector)
    magnitude = norm(next)
    // A zero product means the matrix has no remaining variance in this
    // subspace (fully deflated). Report zero rather than dividing by it.
    if (magnitude < 1e-300) return { value: 0, vector }
    for (let i = 0; i < n; i += 1) next[i] = (next[i] ?? 0) / magnitude
    // Rayleigh quotient; for a unit vector this is vᵗ·M·v.
    let rayleigh = 0
    const product = matVec(matrix, n, next)
    for (let i = 0; i < n; i += 1) rayleigh += (next[i] ?? 0) * (product[i] ?? 0)
    const converged = Math.abs(rayleigh - value) < tolerance * Math.max(1, Math.abs(rayleigh))
    value = rayleigh
    vector = next
    if (converged && step > 8) break
  }
  return { value, vector }
}

type Projection = {
  coords: { x: number; y: number }[]
  component1: number[]
  component2: number[]
  mean: number[]
  explained: number
  explained1: number
  explained2: number
  scale: number
}

function pca2(chunks: Chunk[]): Projection {
  const n = chunks.length
  const first = chunks[0]
  if (!first) throw new Error('pca2 called with no chunks')
  const d = first.embedding.length

  /* Mean-centring is not optional. The vectors are L2-normalised, so they all
     sit on the unit sphere and share a large common direction; skipping the
     centring makes the first "component" that shared direction and wastes the
     axis on a constant. */
  const mean = new Float64Array(d)
  for (const chunk of chunks) {
    for (let j = 0; j < d; j += 1) mean[j] = (mean[j] ?? 0) + (chunk.embedding[j] ?? 0)
  }
  for (let j = 0; j < d; j += 1) mean[j] = (mean[j] ?? 0) / n

  const centred = new Float64Array(n * d)
  for (let i = 0; i < n; i += 1) {
    const embedding = chunks[i]?.embedding ?? []
    for (let j = 0; j < d; j += 1) {
      centred[i * d + j] = (embedding[j] ?? 0) - (mean[j] ?? 0)
    }
  }

  // Gram matrix G = X·Xᵗ (n x n, symmetric).
  const gram = new Float64Array(n * n)
  for (let i = 0; i < n; i += 1) {
    for (let k = i; k < n; k += 1) {
      let sum = 0
      for (let j = 0; j < d; j += 1) sum += (centred[i * d + j] ?? 0) * (centred[k * d + j] ?? 0)
      gram[i * n + k] = sum
      gram[k * n + i] = sum
    }
  }

  /* trace(G) is the total squared deviation of the corpus, which is total
     variance up to the same 1/(n-1) factor that divides out of the ratio. So
     the explained-variance figure printed in the generated file needs no
     scaling assumption — it is λ/trace, exactly. */
  let trace = 0
  for (let i = 0; i < n; i += 1) trace += gram[i * n + i] ?? 0

  const first_ = powerIteration(gram, n)

  // Deflate: remove the first component's rank-one contribution.
  const deflated = Float64Array.from(gram)
  for (let i = 0; i < n; i += 1) {
    for (let k = 0; k < n; k += 1) {
      deflated[i * n + k] =
        (deflated[i * n + k] ?? 0) -
        first_.value * (first_.vector[i] ?? 0) * (first_.vector[k] ?? 0)
    }
  }
  const second = powerIteration(deflated, n)

  // scores = √λ · u  (see the derivation in the block comment above).
  const root1 = Math.sqrt(Math.max(first_.value, 0))
  const root2 = Math.sqrt(Math.max(second.value, 0))
  const rawX = Array.from({ length: n }, (_, i) => root1 * (first_.vector[i] ?? 0))
  const rawY = Array.from({ length: n }, (_, i) => root2 * (second.vector[i] ?? 0))

  /* Sign is arbitrary in an eigenvector — u and -u are both valid. Pin it so
     the map does not mirror itself between builds: force the first chunk (the
     CV header) to land in the negative-x, negative-y quadrant. */
  const flipX = (rawX[0] ?? 0) > 0 ? -1 : 1
  const flipY = (rawY[0] ?? 0) > 0 ? -1 : 1

  /* ONE divisor for both axes, deliberately. Normalising each axis to fill
     [-1,1] independently would stretch the second component until it looked
     as important as the first, which is a lie the picture would tell for
     free. A shared scale keeps the aspect ratio truthful: the spread you see
     along y really is smaller than the spread along x. */
  let scale = 0
  for (let i = 0; i < n; i += 1) {
    scale = Math.max(scale, Math.abs(rawX[i] ?? 0), Math.abs(rawY[i] ?? 0))
  }
  if (scale === 0) scale = 1

  const coords = Array.from({ length: n }, (_, i) => ({
    x: (flipX * (rawX[i] ?? 0)) / scale,
    y: (flipY * (rawY[i] ?? 0)) / scale,
  }))

  // v = Xᵗ·u / √λ, with the same sign flip applied so the emitted component
  // vectors project a new point into the coordinate frame actually plotted.
  function componentVector(u: Float64Array, root: number, flip: number): number[] {
    const out = new Array<number>(d).fill(0)
    if (root === 0) return out
    for (let j = 0; j < d; j += 1) {
      let sum = 0
      for (let i = 0; i < n; i += 1) sum += (u[i] ?? 0) * (centred[i * d + j] ?? 0)
      out[j] = (flip * sum) / root
    }
    return out
  }

  return {
    coords,
    component1: componentVector(first_.vector, root1, flipX),
    component2: componentVector(second.vector, root2, flipY),
    mean: Array.from(mean),
    explained: trace > 0 ? (first_.value + second.value) / trace : 0,
    explained1: trace > 0 ? first_.value / trace : 0,
    explained2: trace > 0 ? second.value / trace : 0,
    scale,
  }
}

/* ==========================================================================
   LABELS

   Each point needs a name a human can read at a glance. The chunks are
   markdown with the whitespace collapsed, so the first phrase is almost
   always the heading it came from — cut it at the first boundary that reads
   like the end of a title and cap it at 40 characters on a word break.
   ========================================================================== */

const LABEL_MAX = 40

function labelFor(text: string): string {
  let head = text.replace(/\s+/g, ' ').trim()
  head = head.replace(/^[#*\-\s]+/, '')

  /* Boundaries, in the order they tend to appear: a question mark ends an FAQ
     heading; `**` starts the first bold field of a body; ` - ` starts the
     first bullet; a full stop ends a sentence. Take the earliest one that
     leaves something substantial behind. */
  const cuts: number[] = []
  const question = head.indexOf('?')
  if (question > 3) cuts.push(question + 1)
  for (const marker of ['**', ' - ', '. ', ' — ']) {
    const at = head.indexOf(marker)
    if (at > 3) cuts.push(at)
  }
  const cut = cuts.length > 0 ? Math.min(...cuts) : head.length
  head = head.slice(0, cut).trim()

  if (head.length > LABEL_MAX) {
    const clipped = head.slice(0, LABEL_MAX)
    const space = clipped.lastIndexOf(' ')
    head = (space > 12 ? clipped.slice(0, space) : clipped).trim()
  }

  // Trailing joiners look like a truncation bug rather than a label.
  head = head.replace(/[\s:;,\-—–(]+$/, '')
  return head.length > 0 ? head : 'untitled chunk'
}

/** `01-portfolio-rag` reads as noise in a legend; `portfolio-rag` does not. */
function sourceLabel(source: string): string {
  return source.replace(/^\d+[-_]/, '')
}

/* ==========================================================================
   BPE TRAINING

   ── WHY TRAIN ONE INSTEAD OF SHIPPING GPT'S ───────────────────────────────
   `gpt-tokenizer` is the honest-looking choice and the wrong one here: it is
   a ~2 MB vocabulary to make chips appear next to a textarea, which on a site
   that argues for performance would be an argument against itself. Training
   on the 23 chunks costs ~4 KB in the bundle and produces a tokeniser that is
   genuinely, verifiably real — the same greedy-merge algorithm, just a much
   smaller corpus. The instrument says so in as many words, and the smallness
   is the interesting part: it makes visible what a vocabulary IS by showing
   one that only knows this website.

   ── THE ALGORITHM ─────────────────────────────────────────────────────────
   Textbook BPE:
     1. Pre-tokenise, keeping each word's leading whitespace attached to it
        (GPT-2 does the same, which is why " the" and "the" are different
        tokens in every real model). Without this, merges leak across word
        boundaries and the vocabulary fills with junk like "e t".
     2. Represent every distinct pre-token as a list of characters, with the
        number of times it occurs in the corpus.
     3. Count every adjacent symbol pair, weighted by those occurrence counts.
     4. Merge the most frequent pair everywhere. Record it.
     5. Repeat 300 times.
   The ORDER of that list is the whole model: the encoder replays the merges
   by rank, which is why a merge table and not just a vocabulary is emitted.
   ========================================================================== */

const MERGE_TARGET = 300

/**
 * Key separator for pair lookups.
 *
 * It has to be a character the corpus cannot contain, and it cannot be a
 * space: tokens legitimately CONTAIN spaces (" the" is one symbol), so
 * `${a} ${b}` would make the pair ("a", " b") and the pair ("a ", "b")
 * produce the same key and silently mis-rank one of them. Written as an
 * escape rather than a literal NUL byte, because an invisible control
 * character in source is unreadable and confuses grep and editors.
 */
const PAIR_SEP = '\u0000'

/** Splits into pre-tokens, leading whitespace bound to the following word. */
export function preTokenise(text: string): string[] {
  return text.match(/\s*\S+|\s+/g) ?? []
}

type TrainedBpe = {
  merges: [string, string][]
  vocab: string[]
  baseChars: string[]
}

function trainBpe(chunks: Chunk[]): TrainedBpe {
  const frequencies = new Map<string, number>()
  for (const chunk of chunks) {
    for (const word of preTokenise(chunk.text)) {
      frequencies.set(word, (frequencies.get(word) ?? 0) + 1)
    }
  }

  // Array.from(string) splits on code points, not UTF-16 units, so an emoji
  // or an em dash stays one symbol instead of becoming two broken halves.
  const words: { symbols: string[]; freq: number }[] = []
  const baseChars = new Set<string>()
  for (const [word, freq] of frequencies) {
    const symbols = Array.from(word)
    for (const character of symbols) baseChars.add(character)
    words.push({ symbols, freq })
  }

  const merges: [string, string][] = []
  const learned = new Set<string>()

  for (let step = 0; step < MERGE_TARGET; step += 1) {
    const pairCounts = new Map<string, number>()
    for (const word of words) {
      const { symbols, freq } = word
      for (let i = 0; i < symbols.length - 1; i += 1) {
        const a = symbols[i]
        const b = symbols[i + 1]
        if (a === undefined || b === undefined) continue
        const key = `${a}${PAIR_SEP}${b}`
        pairCounts.set(key, (pairCounts.get(key) ?? 0) + freq)
      }
    }

    /* Pick the most frequent pair, breaking ties by the key so the result does
       not depend on Map iteration order. Determinism matters: the merge table
       is committed, and a rebuild that reshuffles equal-frequency merges would
       churn the diff for no semantic change. */
    let bestKey: string | null = null
    let bestCount = 0
    for (const [key, count] of pairCounts) {
      if (count > bestCount || (count === bestCount && bestKey !== null && key < bestKey)) {
        bestKey = key
        bestCount = count
      }
    }

    // Stop when nothing repeats: a merge seen once compresses nothing and only
    // memorises a single word in the corpus.
    if (bestKey === null || bestCount < 2) {
      console.log(
        `build-lab-data: BPE converged after ${step} merges (no pair occurs twice)`,
      )
      break
    }

    const [a = '', b = ''] = bestKey.split(PAIR_SEP)
    const merged = a + b
    merges.push([a, b])
    learned.add(merged)

    for (const word of words) {
      const { symbols } = word
      if (symbols.length < 2) continue
      const next: string[] = []
      let i = 0
      while (i < symbols.length) {
        const current = symbols[i]
        const following = symbols[i + 1]
        if (current === a && following === b) {
          next.push(merged)
          i += 2
        } else if (current !== undefined) {
          next.push(current)
          i += 1
        } else {
          i += 1
        }
      }
      word.symbols = next
    }
  }

  const sortedChars = [...baseChars].sort()
  return {
    merges,
    vocab: [...sortedChars, ...learned],
    baseChars: sortedChars,
  }
}

/* --- Encoder (mirrors components/lab/Tokenizer.tsx) -----------------------
   Duplicated here rather than imported so the script can report a real
   compression figure on the training corpus itself. Twenty lines of exact
   duplication is a better trade than a shared module that would drag the
   generated data into the build script's import graph.                     */

function encodeWith(merges: [string, string][], text: string): string[] {
  const ranks = new Map<string, number>()
  merges.forEach(([a, b], index) => ranks.set(`${a}${PAIR_SEP}${b}`, index))

  const out: string[] = []
  for (const word of preTokenise(text)) {
    const symbols = Array.from(word)
    while (symbols.length > 1) {
      let bestRank = Infinity
      let bestIndex = -1
      for (let i = 0; i < symbols.length - 1; i += 1) {
        const a = symbols[i]
        const b = symbols[i + 1]
        if (a === undefined || b === undefined) continue
        const rank = ranks.get(`${a}${PAIR_SEP}${b}`)
        if (rank !== undefined && rank < bestRank) {
          bestRank = rank
          bestIndex = i
        }
      }
      if (bestIndex < 0) break
      const a = symbols[bestIndex]
      const b = symbols[bestIndex + 1]
      if (a === undefined || b === undefined) break
      symbols.splice(bestIndex, 2, a + b)
    }
    out.push(...symbols)
  }
  return out
}

/* ==========================================================================
   ASK CORPUS — the retrieval index behind components/sections/AskPortfolio.tsx

   ── WHY THE RAG INDEX IS NOT ENOUGH ON ITS OWN ────────────────────────────
   The 23 chunks above are the corpus that was embedded, and they are real, but
   they were cut from the CV, the FAQ and the intros BEFORE the case studies
   existed. They describe the CRM as "Stack (frontend, backend, DB, hosting)"
   — an outline, not an answer. Meanwhile content/projects.ts contains the
   finished thing: 197 schema-validated routes, the IDOR the self-run security
   audit found, the RFC-4180 importer. A retrieval system that refuses "what
   did the security audit find?" while the answer sits two files away is not
   being honest, it is being under-indexed.

   So the retrieval corpus is the union: the 23 embedded chunks, plus chunks
   cut here from the site's own current content. Nothing is invented. Every
   supplementary chunk is prose already published on a route a visitor can
   open, which is exactly what makes the citation checkable.

   ── WHY THIS IS GENERATED RATHER THAN IMPORTED AT RUNTIME ─────────────────
   lib/retrieval.ts runs in the browser, so whatever it imports ships. Reaching
   for content/projects.ts directly would pull 40 KB of source — every stack
   rationale, every architecture node, every failure mode — into the home
   page's bundle to quote maybe six sentences of it. Cutting the chunks at
   build time ships the text and nothing else, and it means the corpus is a
   committed artefact: a diff in it is a content change, reviewable as one.

   The 23 embedded chunks are NOT copied in. The generated module imports
   LAB_POINTS and wraps them, because the Lab already ships that text on the
   same page — copying it would be paying for the corpus twice.
   ========================================================================== */

/** Longest a supplementary chunk may be, in characters.

    BM25's length normalisation (b = 0.75) handles uneven documents perfectly
    well, so this is not a scoring concern — it is a citation concern. The
    answer quotes whole sentences out of the winning chunk, and a chunk that
    spans two subjects will sometimes win on one and get quoted on the other.
    ~900 characters is around four sentences of this prose: long enough to keep
    a paragraph's argument intact, short enough that it is about one thing. */
const ASK_CHUNK_MAX = 900

/** Below this, a chunk is a fragment rather than a passage, and BM25's length
    normalisation turns it into a false positive magnet. Merged into a
    neighbour instead of indexed alone. */
const ASK_CHUNK_MIN = 140

