type AskChunk = {
  id: string
  source: string
  label: string
  href: string | null
  text: string
}

/** Collapses whitespace and normalises the typographic characters that make a
    quoted sentence look mangled when it is pulled out of prose. */
function flatten(text: string): string {
  return text.replace(/\s+/g, ' ').trim()
}

/**
 * Splits prose into sentences, then packs them into chunks of at most
 * ASK_CHUNK_MAX characters.
 *
 * Sentence-aware packing rather than a hard character slice, because a chunk
 * that ends mid-sentence produces a citation that ends mid-sentence, and the
 * whole promise of this feature is that what you read is what he wrote.
 */
function packSentences(text: string): string[] {
  const flat = flatten(text)
  if (flat.length <= ASK_CHUNK_MAX) return flat.length > 0 ? [flat] : []

  /* Conservative sentence boundary: a terminator, whitespace, then something
     that starts a sentence. Written as a match rather than a split with a
     lookbehind, because lookbehind is still not universal in Safari and a
     regex that throws at parse time would take the whole module with it. */
  const pieces = flat.match(/[^.!?]+[.!?]+(?=\s|$)\s*|[^.!?]+$/g) ?? [flat]

  const out: string[] = []
  let current = ''
  for (const piece of pieces) {
    const next = current.length > 0 ? `${current}${piece}` : piece
    if (next.length > ASK_CHUNK_MAX && current.length > 0) {
      out.push(current.trim())
      current = piece
    } else {
      current = next
    }
  }
  if (current.trim().length > 0) out.push(current.trim())

  /* Merge runt chunks into their neighbour.

     BM25 normalises by document length, so a very short chunk that happens to
     contain two of the query's terms outranks a long, genuinely relevant one.
     A real case: the six-word chunk "Chose: Build the signing flow in the CRM."
     beat the whole write-up of working with an AI pair on the query "did he
     use AI to build the CRM?" — it contained "build" and "CRM" and nothing
     else, so its term density was unbeatable and its relevance was nil.

     Merging runts forward keeps every chunk long enough for length
     normalisation to mean something. It is a retrieval-quality fix rather than
     a fix for one query: any sentence short enough to be a label was always
     going to win queries it should lose. */
  const merged: string[] = []
  for (const piece of out) {
    const previous = merged[merged.length - 1]
    if (piece.length < ASK_CHUNK_MIN && previous !== undefined) {
      merged[merged.length - 1] = `${previous} ${piece}`.trim()
    } else {
      merged.push(piece)
    }
  }

  /* A leading runt has no previous neighbour, so it merges backwards into the
     one that follows it instead. */
  if (merged.length > 1 && (merged[0]?.length ?? 0) < ASK_CHUNK_MIN) {
    merged[1] = `${merged[0]} ${merged[1]}`.trim()
    merged.shift()
  }

  return merged
}

/** ~52 characters of human label, so a source chip reads as a place. */
function shortLabel(text: string): string {
  const flat = flatten(text)
  if (flat.length <= 52) return flat
  const clipped = flat.slice(0, 52)
  const space = clipped.lastIndexOf(' ')
  return `${(space > 20 ? clipped.slice(0, space) : clipped).replace(/[\s,;:—–-]+$/, '')}…`
}

/**
 * Cuts the supplementary chunks out of the site's own content modules.
 *
 * Deliberately NOT everything. The CV is skipped entirely, because the 23
 * embedded chunks already are the CV — indexing it twice would put two
 * near-identical documents at the top of every employment query and cost the
 * bundle for the privilege. What is added is the two bodies of prose the index
 * has never seen: the about page, and the ten-part case studies.
 */
async function buildAskSupplement(): Promise<AskChunk[]> {
  /* Imported for their real, validated shape rather than parsed out of the
     source text. lib/content.ts runs every project through Zod at module load,
     so a corpus built from it cannot contain a chunk that the site itself would
     refuse to render. */
  const { projects, hasProjectPage, decisions, incidents } = await import('../lib/content')
  const { site } = await import('../lib/site.config')

  const chunks: AskChunk[] = []
  const add = (source: string, href: string | null, label: string, text: string): void => {
    for (const [index, part] of packSentences(text).entries()) {
      chunks.push({
        id: `${source}-${String(chunks.length + 1).padStart(2, '0')}`,
        source,
        href,
        label: index === 0 ? label : `${label} (cont.)`,
        text: part,
      })
    }
  }

  /* --- The about page ---------------------------------------------------- */
  for (const section of site.about.sections) {
    /* The heading is prepended to the body because it carries terms the body
       assumes: "What I have learned" is where the security-audit lesson lives,
       and the body never uses the word "learned". */
    add('about', '/about', section.heading, `${section.heading}. ${section.body}`)
  }
  add(
    'about',
    '/about',
    'Timeline',
    `Timeline. ${site.about.timeline.map((entry) => `${entry.year}: ${entry.event}`).join(' ')}`,
  )

  /* One templated chunk, and the only templated one. Every value in it is a
     field of site.config — location, timezone, availability, role, email — and
     the sentence exists because the structured fields say "Gurgaon, India"
     while a visitor asks "where is he based?". Retrieval matches words, so the
     words a person would use have to be in the corpus somewhere. This is
     formatting, not authorship: no claim here that site.config does not make. */
  add(
    'profile',
    '/about',
    'Location and availability',
    `Location and availability. ${site.name} is based in ${site.location}, and works in ` +
      `the ${site.timezone} time zone (${site.timezoneLabel}). His role is ${site.role}. ` +
      `Current status: ${site.availability}. He can be reached by email at ${site.email}.`,
  )

  /* --- The case studies -------------------------------------------------- */
  /* Adds a chunk only when the field exists. With the depth ladder in
     lib/schema.ts, six of the ten case-study parts are absent on a supporting
     project and most are absent on an archive entry — so this is now the
     normal case, not an edge case. Skipping is the whole behaviour: a chunk
     built from an undefined field would index the string "undefined" and the
     retrieval probes would start matching it. */
  const addIf = (
    source: string,
    href: string | null,
    label: string,
    text: string | undefined,
  ): void => {
    if (text) add(source, href, label, text)
  }

  for (const project of projects) {
    const source = `work/${project.slug}`
    /* Archive entries have no page (lib/content.ts, hasProjectPage), so their
       chunks cite the work index. Citing /work/<slug> would hand the chat a
       confident link to a 404 — the one failure mode that makes a retrieval
       answer worse than no answer. */
    const href = hasProjectPage(project) ? `/work/${project.slug}` : '/work'

    /* An overview chunk, assembled from the project's structured fields, so a
       query naming the technology finds the project even when the prose below
       never spells the stack out in one place. */
    const stack = project.stack.map((item) => item.name).join(', ')
    add(
      source,
      href,
      project.title,
      `${project.title}. ${project.tagline} Role: ${project.role}. Status: ${project.status}, ` +
        `${project.year}${project.duration ? `, ${project.duration}` : ''}. ` +
        `Built for ${project.client ?? project.clientDescriptor ?? 'an undisclosed client'}. ` +
        `Stack: ${stack}.`,
    )

    add(source, href, `${project.title} — context`, project.context)
    addIf(source, href, `${project.title} — the problem`, project.problem)
    addIf(source, href, `${project.title} — approach`, project.approach)
    addIf(source, href, `${project.title} — implementation`, project.implementation)

    /* One chunk per challenge, rather than one chunk listing all of them.
       The items are separate statements and most do not end in a full stop, so
       joining them produces a single run-on "sentence" — and the quotation for
       "what did the security audit find?" came back as the CSV-parsing
       challenge, because both were inside the same unbreakable blob. Splitting
       at the boundary that already exists in the data is better than inserting
       punctuation he did not write. */
    const challenges = project.challenges ?? []
    for (const [index, challenge] of challenges.entries()) {
      add(
        source,
        href,
        `${project.title} — what was hard (${index + 1}/${challenges.length})`,
        challenge,
      )
    }
    addIf(source, href, `${project.title} — how it was solved`, project.solution)
    add(source, href, `${project.title} — outcome`, project.outcome)
    addIf(source, href, `${project.title} — in hindsight`, project.reflection)


  /* Metrics are templated from the same objects the case-study page renders,
       including the source and capture date. A number without its provenance
       is exactly what lib/schema.ts exists to prevent, so the provenance
       travels with it into the corpus. */
    if (project.metrics.length > 0) {
      const measured = project.metrics
        .map(
          (metric) =>
            `${metric.label}: ${metric.after}` +
            `${metric.before ? ` (from ${metric.before})` : ''}` +
            ` — ${metric.source}, measured ${metric.capturedAt}.` +
            `${metric.note ? ` ${metric.note}` : ''}`,
        )
        .join(' ')
      add(source, href, `${project.title} — measured results`, `Measured results. ${measured}`)
    }
  }

    /* --- The decision log and the failure archive --------------------------

     These were missing from the corpus, and their absence was worse than a
     gap: they are the highest-signal content on the site, and leaving them
     out meant the chat refused questions the site answers in full three
     clicks away. On one topic in particular that refusal read as evasion
     rather than as honest scope — "did you use AI to build this?" is
     documented as a decision with its trade-off paid in the failure archive,
     and a chat that says "there is nothing here about that" about openly
     published content is not being careful, it is being wrong.

     Each decision is split at its own field boundaries rather than indexed as
     one blob, for the same reason the challenges are: "what did you trade
     away" and "what happened" are different questions and want to be
     different chunks. */
  for (const decision of decisions) {
    const source = `thinking/${decision.id}`
    const href = `/thinking#${decision.id}`

    /* The projects a decision belongs to are named INSIDE its chunks, not just
       linked from them. Without this, "did he use AI to build the CRM?" scored
       the e-signatures decision higher than the one about working with an AI
       pair — because that chunk happened to contain both "build" and "CRM"
       while the right answer contained neither. BM25 cannot know that a
       decision tagged `projects: ['crm']` is about the CRM; the vocabulary has
       to actually be in the text. */
    const about = decision.projects
      .map((slug) => projects.find((p) => p.slug === slug)?.title)
      .filter((title): title is string => Boolean(title))
    const scope = about.length > 0 ? ` This decision is about ${about.join(' and ')}.` : ''

    add(source, href, decision.question, `${decision.question} ${decision.context}${scope}`)
    add(
      source,
      href,
      `${decision.question} — what was chosen`,
      `Chose: ${decision.chose}. ${decision.because}${scope}`,
    )
    add(source, href, `${decision.question} — the trade-off`, decision.tradeoff)
    add(
      source,
      href,
      `${decision.question} — outcome`,
      `${decision.outcome} Would do it again: ${decision.wouldRepeat}.`,
    )
    for (const option of decision.options) {
      const pros = option.pros.join('. ')
      const cons = option.cons.join('. ')
      add(
        source,
        href,
        `${decision.question} — option considered: ${option.name}`,
        `${option.name}. In favour: ${pros}. Against: ${cons}.`,
      )
    }
  }

  for (const incident of incidents) {
    const source = `failures/${incident.id}`
    const href = `/thinking#${incident.id}`
    add(source, href, `${incident.title} — what happened`, `${incident.symptom} ${incident.impact}`)
    add(source, href, `${incident.title} — cause`, incident.cause)
    add(source, href, `${incident.title} — the fix`, incident.fix)
    add(source, href, `${incident.title} — what it taught`, incident.lesson)
  }

  return chunks
}

/* ==========================================================================
   WITHHELD TOPICS — the questions the site deliberately does not answer

   Retrieval can only refuse two ways on its own: nothing matched, or nothing
   matched well enough. Neither covers the case where the corpus contains the
   QUESTION but not the ANSWER — lib/site.config.ts lists a notice period and a
   visa status as fields, and their values are still `[TO CONFIRM]`. BM25 sees
   the label, scores the chunk, and would quote a field name back as though it
   were a fact.

   So the unfilled logistics fields are emitted as explicit withheld topics,
   derived from the same placeholders that `npm run check:content` already
   reports. This is not a blocklist of awkward questions: it is the honest
   consequence of a field that has no value yet, and when Dheeraj fills one in,
   the next build drops it from this list automatically.
   ========================================================================== */

/* Two regexes for one pattern on purpose: a /g regex carries lastIndex between
   calls, so using the same object to test and to strip makes the second call
   depend on where the first one stopped. */
const HAS_PLACEHOLDER = /\[[^\]]+\]/
const ALL_PLACEHOLDERS = /\[[^\]]+\]/g

type Withheld = { topic: string; terms: string[]; reason: string }

async function buildWithheld(): Promise<Withheld[]> {
  const { site } = await import('../lib/site.config')
  const stopwords = new Set(['to', 'in', 'of', 'or', 'and', 'the', 'a', 'an'])

  const out: Withheld[] = []
  for (const field of site.cv.logistics) {
    if (!HAS_PLACEHOLDER.test(field.value)) continue

    /* Whatever survives once the placeholder is removed is a real stated
       position — "Salary expectations: Discussed at offer stage." is a stance,
       even though the bracketed note beside it is unresolved. It becomes the
       refusal's reason, so the refusal says what the site says rather than
       inventing a softer version of it. */
    const stated = field.value.replace(ALL_PLACEHOLDERS, '').replace(/\s+/g, ' ').trim()

    const terms = field.label
      .toLowerCase()
      .split(/[^a-z0-9]+/)
      .filter((term) => term.length > 1 && !stopwords.has(term))

    out.push({
      topic: field.label.toLowerCase(),
      terms,
      reason:
        stated.length > 0
          ? `On “${field.label.toLowerCase()}” the CV states only this: ${stated} Anything more precise is Dheeraj's to tell you himself.`
          : `The CV lists “${field.label.toLowerCase()}” as a field and leaves its value to be confirmed, so there is nothing published here to quote.`,
    })
  }
  return out
}

